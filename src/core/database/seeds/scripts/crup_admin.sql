-- TABLA PERFIL

-- Ver todos los perfiles
SELECT * FROM PERFIL ORDER BY CODIGO_PERFIL;

-- Ver perfiles con su rol
SELECT P.CODIGO_PERFIL, P.NOMBRE_PERFIL, R.NOMBRE_ROL
FROM PERFIL P
JOIN ROL R ON R.ID_ROL = P.ID_ROL
ORDER BY R.NOMBRE_ROL, P.NOMBRE_PERFIL;

-- Ver perfiles por rol
SELECT P.CODIGO_PERFIL, P.NOMBRE_PERFIL
FROM PERFIL P
JOIN ROL R ON R.ID_ROL = P.ID_ROL
WHERE R.NOMBRE_ROL = 'ESTUDIANTE';

-- Ver un perfil específico
SELECT * FROM PERFIL WHERE CODIGO_PERFIL = 1;
SELECT * FROM PERFIL WHERE NOMBRE_PERFIL = 'AdministradorGeneral';

-- Ver cuántos usuarios tiene cada perfil
SELECT P.NOMBRE_PERFIL, R.NOMBRE_ROL, COUNT(U.ID_USER) AS TOTAL_USUARIOS
FROM PERFIL P
JOIN ROL R ON R.ID_ROL = P.ID_ROL
LEFT JOIN USUARIO U ON U.CODIGO_PERFIL = P.CODIGO_PERFIL
GROUP BY P.NOMBRE_PERFIL, R.NOMBRE_ROL
ORDER BY TOTAL_USUARIOS DESC;

-- Insertar un perfil
INSERT INTO PERFIL (NOMBRE_PERFIL, ID_ROL) VALUES ('Nuevo Perfil', 3);

-- Actualizar un perfil
UPDATE PERFIL SET NOMBRE_PERFIL = 'Nuevo Nombre' WHERE CODIGO_PERFIL = 1;
UPDATE PERFIL SET ID_ROL = 2 WHERE CODIGO_PERFIL = 1;

-- Eliminar un perfil (solo si no tiene usuarios asociados)
DELETE FROM PERFIL WHERE CODIGO_PERFIL = 1;

-- =====================================================
-- TABLA MENU
-- =====================================================

-- Ver todos los menús
SELECT * FROM MENU ORDER BY CODIGO_MENU;

-- Ver menús con su padre
SELECT M.CODIGO_MENU, M.NOMBRE_MENU, M.URL_MENU,
       MP.NOMBRE_MENU AS MENU_PADRE
FROM MENU M
LEFT JOIN MENU MP ON MP.CODIGO_MENU = M.MENU_PADRE_CODIGO
ORDER BY M.CODIGO_MENU;

-- Ver solo menús padre (sin padre)
SELECT * FROM MENU WHERE MENU_PADRE_CODIGO IS NULL;

-- Ver submenús de un menú padre
SELECT * FROM MENU WHERE MENU_PADRE_CODIGO = 'M001';

-- Ver menús con sus permisos por perfil
SELECT M.NOMBRE_MENU, P.NOMBRE_PERFIL,
       MP.PUEDE_CREAR, MP.PUEDE_LEER,
       MP.PUEDE_ACTUALIZAR, MP.PUEDE_ELIMINAR
FROM MENU_PERMISO MP
JOIN MENU M ON M.CODIGO_MENU = MP.CODIGO_MENU
JOIN PERFIL P ON P.CODIGO_PERFIL = MP.CODIGO_PERFIL
ORDER BY M.NOMBRE_MENU, P.NOMBRE_PERFIL;

