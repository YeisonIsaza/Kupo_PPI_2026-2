FROM UNIVERSIDAD U
LEFT JOIN UNIVERSIDAD_ESTUDIANTE UE ON UE.NIT_UNI = U.NIT_UNI
GROUP BY U.NOMBRE_UNI
ORDER BY TOTAL_ESTUDIANTES DESC;

