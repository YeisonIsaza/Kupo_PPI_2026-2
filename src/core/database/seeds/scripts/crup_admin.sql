SELECT * FROM ESTADO WHERE CATEGORIA = 'VIAJE';
SELECT * FROM ESTADO WHERE CATEGORIA = 'RESERVA';
SELECT * FROM ESTADO WHERE CATEGORIA = 'RUTA';
SELECT * FROM ESTADO WHERE CATEGORIA = 'VINCULACION';
