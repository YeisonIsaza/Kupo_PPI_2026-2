-- Eliminar un estado (solo si no tiene usuarios asociados)
DELETE FROM ESTADO WHERE ID_ESTADO = 1;

-- TABLA UNIVERSIDAD


-- Ver todas las universidades
SELECT * FROM UNIVERSIDAD ORDER BY NOMBRE_UNI;

-- Ver una universidad específica
SELECT * FROM UNIVERSIDAD WHERE NIT_UNI = ' 890.980.040-8';
