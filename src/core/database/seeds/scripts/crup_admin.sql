-- =====================================================
-- TABLA ROL
-- =====================================================

-- Ver todos los roles
SELECT * FROM ROL ORDER BY ID_ROL;

-- Ver un rol específico
SELECT * FROM ROL WHERE ID_ROL = 1;
SELECT * FROM ROL WHERE NOMBRE_ROL = 'ADMINISTRADOR';

-- Insertar un rol
INSERT INTO ROL (NOMBRE_ROL) VALUES ('NUEVO_ROL');

-- Actualizar un rol
UPDATE ROL SET NOMBRE_ROL = 'NOMBRE_NUEVO' WHERE ID_ROL = 1;

-- Eliminar un rol (solo si no tiene perfiles asociados)
DELETE FROM ROL WHERE ID_ROL = 1;

-- Ver cuántos perfiles tiene cada rol
SELECT R.NOMBRE_ROL, COUNT(P.CODIGO_PERFIL) AS TOTAL_PERFILES
FROM ROL R
LEFT JOIN PERFIL P ON P.ID_ROL = R.ID_ROL
GROUP BY R.NOMBRE_ROL
ORDER BY R.NOMBRE_ROL;

