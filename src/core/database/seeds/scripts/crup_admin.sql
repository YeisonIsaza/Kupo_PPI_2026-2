-- Ver todos los usuarios con su perfil, rol y estado
SELECT U.ID_USER, U.NOMBRE_USER, U.APELLIDO_USER,
       U.CORREO_PERSONAL_USER, P.NOMBRE_PERFIL,
       R.NOMBRE_ROL, E.NOMBRE_ESTADO AS ESTADO_CUENTA
FROM USUARIO U
JOIN PERFIL P ON P.CODIGO_PERFIL = U.CODIGO_PERFIL
JOIN ROL R ON R.ID_ROL = P.ID_ROL
JOIN ESTADO E ON E.ID_ESTADO = U.ID_ESTADO_CUENTA
ORDER BY U.ID_USER;

-- Ver usuarios pendientes de aprobación
SELECT U.ID_USER, U.NOMBRE_USER, U.APELLIDO_USER,
       U.CORREO_PERSONAL_USER, P.NOMBRE_PERFIL, R.NOMBRE_ROL
FROM USUARIO U
JOIN PERFIL P ON P.CODIGO_PERFIL = U.CODIGO_PERFIL
JOIN ROL R ON R.ID_ROL = P.ID_ROL
JOIN ESTADO E ON E.ID_ESTADO = U.ID_ESTADO_CUENTA
WHERE E.NOMBRE_ESTADO = 'PENDIENTE' AND E.CATEGORIA = 'VERIFICACION'
ORDER BY U.ID_USER;

-- Ver estudiantes con sus universidades
SELECT U.NOMBRE_USER, U.APELLIDO_USER,
       U.DOCUMENTO_IDENTIDAD_USER,
       UN.NOMBRE_UNI,
       UE.CORREO_INSTITUCIONAL_UNE
FROM UNIVERSIDAD_ESTUDIANTE UE
JOIN USUARIO U ON U.ID_USER = UE.ID_USER
JOIN UNIVERSIDAD UN ON UN.NIT_UNI = UE.NIT_UNI
ORDER BY U.APELLIDO_USER;

-- Ver conductores con su vehículo
SELECT U.NOMBRE_USER, U.APELLIDO_USER,
       C.NUMERO_LICENCIA, C.FECHA_VENCIMIENTO_LICENCIA,
       V.PLACA_VEH, V.MARCA_VEH, V.MODELO_VEH,
       V.TOTAL_CUPOS_VEH
FROM CONDUCTOR C
JOIN USUARIO U ON U.ID_USER = C.ID_USER
JOIN VEHICULO V ON V.ID_USER = C.ID_USER
ORDER BY U.APELLIDO_USER;