VALUES ('M061', '/nueva-seccion/detalle', 'Detalle', 'M006');

-- Actualizar un menú
UPDATE MENU SET NOMBRE_MENU = 'Nuevo Nombre' WHERE CODIGO_MENU = 'M006';
UPDATE MENU SET URL_MENU = '/nueva-url' WHERE CODIGO_MENU = 'M006';
UPDATE MENU SET MENU_PADRE_CODIGO = 'M001' WHERE CODIGO_MENU = 'M006';

-- Eliminar un menú (primero eliminar permisos asociados)
DELETE FROM MENU_PERMISO WHERE CODIGO_MENU = 'M006';
DELETE FROM MENU WHERE CODIGO_MENU = 'M006';

